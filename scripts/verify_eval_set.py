"""Build a worksheet for hand-checking the eval set against the corpus.

The eval set is the answer key every metric in this project is scored against,
and it was drafted mechanically. Until a human has read each `ground_truth`
against the passage it claims to come from, the metrics measure agreement with
an unverified assertion rather than correctness. That is worth exactly nothing,
and it is worse than nothing if it is quoted in a README.

The obvious way to check it -- open 36 government PDFs, find the right page,
read -- takes an afternoon and gets skipped. So this pulls the evidence to the
question instead. For each entry it finds the passages in the gold document that
best support the stated ground_truth and prints them side by side, with page
numbers, so the check becomes reading rather than searching.

What it can and cannot do. It ranks passages by similarity to the ground_truth,
which is a retrieval operation, not a judgement -- it cannot tell you the answer
is *correct*, only where to look. A ground_truth that is confidently wrong will
still surface the passage it was derived from. The human pass is the point; this
only removes the excuse.

    python scripts/verify_eval_set.py                 # everything, as markdown
    python scripts/verify_eval_set.py --id q017       # one question
    python scripts/verify_eval_set.py --category ocr  # one category
    python scripts/verify_eval_set.py --output eval/VERIFICATION.md
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sift.db import connect  # noqa: E402
from sift.embed import embed_passages  # noqa: E402

from eval.retrieval_eval import load_eval_set  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent

# How many supporting passages to show per gold document. Three is enough to
# catch a ground_truth stitched together from two different places, which is the
# failure mode a single passage would hide.
PASSAGES_PER_DOC = 3


def supporting_passages(conn, doc_id: str, ground_truth: str, limit: int = PASSAGES_PER_DOC):
    """Passages from one document, ranked by similarity to the stated answer.

    Deliberately scoped to the gold document rather than the whole corpus. The
    question being checked is "does this document say this?", and searching
    everywhere would answer a different one.
    """
    vector = embed_passages([ground_truth])[0]
    return conn.execute(
        """
        SELECT chunk_index, page_start, page_end, text,
               1 - (embedding <=> %(qvec)s) AS similarity
        FROM chunks
        WHERE doc_id = %(doc_id)s AND embedding IS NOT NULL
        ORDER BY embedding <=> %(qvec)s, chunk_index
        LIMIT %(limit)s
        """,
        {"qvec": vector, "doc_id": doc_id, "limit": limit},
    ).fetchall()


def document_header(conn, doc_id: str) -> dict:
    row = conn.execute(
        "SELECT doc_id, title, url, source, published_year, parse_strategy,"
        " is_scanned, page_count FROM documents WHERE doc_id = %s",
        (doc_id,),
    ).fetchone()
    return dict(row) if row else {"doc_id": doc_id, "title": "(not in corpus)"}


def render(questions: list[dict]) -> str:
    out: list[str] = [
        "# Eval set verification worksheet",
        "",
        "Generated by `scripts/verify_eval_set.py`. For each question: the stated",
        "`ground_truth`, and the passages in the gold document that best support it,",
        "with page numbers.",
        "",
        "**How to use this.** For each entry, decide one of three things:",
        "",
        "- **OK** — the passage says what the ground_truth says. Move on.",
        "- **Fix the ground_truth** — the document says something subtly different",
        "  (a different number, a qualifier, a date). Correct the YAML.",
        "- **Fix the gold_doc_ids** — the answer is real but lives somewhere else,",
        "  or in more documents than are listed.",
        "",
        "Watch specifically for: numbers that lost a qualifier (\"about\", \"at least\"),",
        "dates that belong to a different event in the same sentence, and answers",
        "assembled from two passages that do not sit together in the source.",
        "",
        "Unanswerable questions have no gold document by design — verify instead that",
        "the answer genuinely is **not** in the corpus, which is what makes abstention",
        "the correct behaviour.",
        "",
        "---",
        "",
    ]

    with connect() as conn:
        for q in questions:
            gold = q.get("gold_doc_ids") or []
            out.append(f"## {q['id']} · `{q.get('category', 'factual')}`")
            out.append("")
            out.append(f"**Q.** {q['question']}")
            out.append("")
            out.append("**Stated ground_truth**")
            out.append("")
            out.append("> " + " ".join((q.get("ground_truth") or "").split()))
            out.append("")

            if q.get("notes"):
                out.append(f"*Note in the eval set:* {q['notes']}")
                out.append("")

            if not gold:
                out.append(
                    "**No gold document — this question must be unanswerable.** Confirm the"
                    " corpus really does not contain it; a question that *is* answerable"
                    " but listed here punishes the system for answering correctly."
                )
                out.append("")
                out.append("---")
                out.append("")
                continue

            for doc_id in gold:
                doc = document_header(conn, doc_id)
                scanned = " · **scanned/OCR**" if doc.get("is_scanned") else ""
                pages = f" · {doc['page_count']} pages" if doc.get("page_count") else ""
                out.append(f"**Gold document** `{doc_id}`{scanned}{pages}")
                out.append("")
                out.append(f"- {doc.get('title') or '(untitled)'}")
                if doc.get("url"):
                    out.append(f"- {doc['url']}")
                out.append("")

                rows = supporting_passages(conn, doc_id, q.get("ground_truth") or q["question"])
                if not rows:
                    out.append(
                        "  **No passages found for this document.** Either it failed to"
                        " parse or the id is wrong — check before trusting any metric"
                        " that depends on this question."
                    )
                    out.append("")
                    continue

                for rank, row in enumerate(rows, start=1):
                    page = (
                        f"p. {row['page_start']}"
                        if row["page_start"] == row["page_end"]
                        else f"pp. {row['page_start']}–{row['page_end']}"
                    )
                    out.append(
                        f"<details {'open' if rank == 1 else ''}>"
                        f"<summary>passage {rank} · {page} · similarity {row['similarity']:.3f}"
                        f"</summary>"
                    )
                    out.append("")
                    body = " ".join(row["text"].split())
                    out.append(textwrap.fill(body, width=88))
                    out.append("")
                    out.append("</details>")
                    out.append("")

            out.append("---")
            out.append("")

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--id", action="append", help="only these question ids")
    parser.add_argument("--category", action="append", help="only these categories")
    parser.add_argument(
        "--output",
        type=Path,
        default=REPO_ROOT / "eval" / "VERIFICATION.md",
        help="where to write the worksheet",
    )
    args = parser.parse_args()

    questions = load_eval_set()
    if args.id:
        questions = [q for q in questions if q["id"] in set(args.id)]
    if args.category:
        questions = [q for q in questions if q.get("category") in set(args.category)]
    if not questions:
        raise SystemExit("No questions matched those filters.")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(questions))
    print(f"Wrote {args.output} covering {len(questions)} question(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
